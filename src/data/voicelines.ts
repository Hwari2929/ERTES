/** 문자열 시드로 줄 하나를 고른다 (같은 키면 같은 줄 → 다시 그려도 깜빡이지 않는다) */
export function voicePick(lines: string[] | undefined, key: string): string | null {
  if (!lines?.length) return null;
  let h = 2166136261;
  for (let i = 0; i < key.length; i++) { h ^= key.charCodeAt(i); h = Math.imul(h, 16777619); }
  return lines[(h >>> 0) % lines.length];
}
