/** 실제 전장 id → 위 키. 신규 전장 FieldDef 가 들어오면 여기서 맞춘다 (같으면 비워 둔다) */
export const FIELD_INTRO_ALIAS: Record<string, string> = {};

export function fieldIntroOf(fieldId: string): FieldIntro | null {
  return FIELD_INTROS[FIELD_INTRO_ALIAS[fieldId] || fieldId] || null;
}

/** 런 시작 직후 한 번: 도입 이야기를 미연시 알림(notice + scene)으로 만든다. 저장 · 불러오기는 대기열(pending)이 맡는다 */
export function fieldIntroPending(run: RunState): Pending | null {
  if (run.tutorial || run.flags.includes('field_intro')) return null;
  const fi = fieldIntroOf(run.field);
  if (!fi) return null;
  run.flags.push('field_intro');
  return { t: 'notice', title: `의뢰 — ${fi.title}`, body: `의뢰인 ${fi.client}${fi.reward ? ` · 보상 ${fi.reward}` : ''}`, scene: fi.beats };
}
