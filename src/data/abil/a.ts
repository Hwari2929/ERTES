/** 값이 있을 때만 행 추가 */
const opt = (on: unknown, k: string, v: string): Row[] => (on ? [[k, v]] : []);
/** 값이 있을 때만 상세 문장 추가 */
const optL = (on: unknown, ...lines: string[]): string[] => (on ? lines : []);
/** 상세 문장 조각 (docs/ABILITY_TEXT.md) */
const STUN_TXT = (s: number | string) => `[g:stun] 효과는 대상이 이동 · 공격 · 스킬을 쓰지 못하게 하며, [s:${s}] 지속됩니다.`;
