export const MERCHANT_BY_ID: Record<string, MerchantDef> = Object.fromEntries(MERCHANTS.map((m) => [m.id, m]));
/** 이 전장의 상점에 나올 수 있는 상인: 공용 상인(fields 없음) + 이 전장으로 묶인 상인 + 전장이 더한 특별 상인 (battlefields.ts FieldDef.merchants) */
export function merchantPool(field?: { id: string; merchants?: string[] }): string[] {
  const ids = MERCHANTS.filter((m) => !m.fields || (!!field && m.fields.includes(field.id))).map((m) => m.id);
  for (const id of field?.merchants || []) if (MERCHANT_BY_ID[id] && !ids.includes(id)) ids.push(id);
  return ids;
}
